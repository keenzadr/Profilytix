STRINGS = {"en": {key: key for key in _RU}, "ru": _RU}


def normalize_language(language: object, default: str = "ru") -> str:
    """Validate a saved language code without accepting arbitrary locales."""
    return str(language) if language in STRINGS else default


def tr(template: str, language: str = "en", **values: object) -> str:
    """Translate a whole known template, then interpolate untouched values."""
    text = STRINGS.get(language, STRINGS["en"]).get(template, template)
    return text.format(**values) if values else text
